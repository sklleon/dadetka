#!/usr/bin/env python3
"""Очередь выпусков на Страницу Facebook. Работает НА РАННЕРЕ GitHub, не у нас.

    python3 ig/fb/fb_queue_publish.py --dry   # что пошло бы сегодня, без отправки
    python3 ig/fb/fb_queue_publish.py         # опубликовать один выпуск, если сегодня день очереди

Задание (`fb_queue.json` рядом) собирает `Диктовка/fb_очередь.py` на нашей машине.
Решение и его причины — там же, в докстроке.

⛔ Зачем раннер: домены Meta из России закрыты для публикации, раннеры ходят из США.

─── Почему очередь, а не расписание по датам, как у спринта ───

У спринта каждый пункт привязан к дате: упал запуск — пост потерян, и это
приемлемо для недельного замера. Для шестнадцати выпусков — нет: один сбой
сдвигал бы не дату, а навсегда выбрасывал выпуск из сериала. Поэтому в день
очереди берётся ПЕРВЫЙ невыложенный выпуск, а не «выпуск на сегодня».

─── Защита от дубля, и почему их две ───

1. Отметка «опубликовано» в самом задании, коммитится обратно в репозиторий:
   раннер чистый при каждом запуске и журнала на нём не бывает.
2. Сверка с лентой Страницы по метке «🎙 ЭПИЗОД N» перед публикацией. Отметка
   может не доехать (push упал после успешного поста) — тогда без сверки
   следующий запуск выложил бы тот же выпуск второй раз.
   ⛔ Лента не прочиталась — не публикуем вовсе: сверка, которую пропустили
   молча, хуже отсутствующей, потому что выглядит сделанной.
"""
import datetime
import json
import os
import pathlib
import re
import sys
import urllib.parse
import urllib.request

ЗАДАНИЕ = pathlib.Path(__file__).resolve().parent / "fb_queue.json"
API = "https://graph.facebook.com/v21.0"

# ⚠️ Части одного выпуска — разные метки. Метка очереди Threads сводит
# «ЭПИЗОД 9 · ч. 1» и «ч. 2» к одному «Эп.9», и после первой части сверка
# вернула бы её в очередь как невыложенную (найдено 15.09.2026).
_МЕТКА = re.compile(r"^\W*(ЭПИЗОД|СПЕЦВЫПУСК)\s+№?(\d+)(?:\s*·\s*ч\.\s*(\d+))?", re.I)


def метка(текст):
    """«🎙 ЭПИЗОД 9 · ч. 1\\n…» → «Эп.9 ч.1». Не выпуск — None."""
    м = _МЕТКА.match(текст or "")
    if not м:
        return None
    имя = ("Эп." if м.group(1).upper() == "ЭПИЗОД" else "Спец.") + м.group(2)
    return имя + (f" ч.{м.group(3)}" if м.group(3) else "")


def сегодня_мск():
    """Раннер живёт в UTC, дни очереди написаны по-московски."""
    return (datetime.datetime.now(datetime.timezone.utc) + datetime.timedelta(hours=3)).date()


def решить(задание, сегодня, на_странице):
    """Что публиковать сегодня. → (пункт или None, объяснение).

    Чистая функция: сеть и файл — снаружи, чтобы каждое «нет» проверялось тестом.
    `на_странице` — метки выпусков в ленте Страницы; None — лента не прочиталась.
    """
    старт = datetime.date.fromisoformat(задание["старт"])
    if сегодня < старт:
        return None, f"очередь стартует {старт:%d.%m.%Y} — до этого молчу"
    if сегодня.weekday() not in задание["дни"]:
        return None, "сегодня не день очереди — молчу"
    for п in задание["items"]:
        о = п.get("опубликовано") or {}
        if о.get("дата") == сегодня.isoformat():
            return None, f"сегодня уже вышел {п['метка']} — второй пост за день не шлю"
    if на_странице is None:
        return None, "ленту Страницы прочитать не удалось — без сверки не публикую"
    for п in задание["items"]:
        if п.get("опубликовано"):
            continue
        if п["метка"] in на_странице:
            # Пост есть, отметки нет: push отметки не доехал. Когда именно вышел
            # пост, отсюда не видно — мог и сегодня, при ручном перезапуске. Поэтому
            # помечаем и молчим до следующего дня очереди: пропуск дня дешевле
            # двух выпусков подряд.
            п["опубликовано"] = {"дата": None, "id": None, "как": "найден в ленте Страницы"}
            return None, f"{п['метка']} уже на Странице без отметки — отметил, сегодня молчу"
        return п, f"следующий: {п['метка']}"
    return None, "очередь пуста — все выпуски на Странице"


def лента(страница, токен):
    """Метки выпусков в ленте Страницы. None — если не ответила."""
    поля = urllib.parse.urlencode({"fields": "message", "limit": "100", "access_token": токен})
    try:
        с = urllib.request.urlopen(f"{API}/{страница}/published_posts?{поля}", timeout=60)
        данные = json.loads(с.read())["data"]
    except Exception:                                   # noqa: BLE001
        return None
    return {м for м in (метка(x.get("message")) for x in данные) if м}


def главная():
    сухо = "--dry" in sys.argv
    токен = os.environ.get("META_PAGE_TOKEN", "")
    страница = os.environ.get("FB_PAGE_ID", "")
    задание = json.loads(ЗАДАНИЕ.read_text(encoding="utf-8"))
    сегодня = сегодня_мск()

    на_странице = лента(страница, токен) if токен and страница else None
    п, почему = решить(задание, сегодня, на_странице)
    # Отметки «найден в ленте» сохраняем даже без публикации.
    ЗАДАНИЕ.write_text(json.dumps(задание, ensure_ascii=False, indent=1), encoding="utf-8")
    print(f"📅 {сегодня:%d.%m.%Y} · {почему}")
    if сухо:
        # До старта решение молчит раньше, чем видно, живы ли секреты и чтение
        # ленты. Сухой прогон называет это отдельно — иначе первая проверка
        # доступа случилась бы в момент первой публикации (15.09.2026).
        print("🔑 ключей в окружении нет" if not (токен and страница) else
              "⛔ лента Страницы не прочиталась" if на_странице is None else
              f"✅ лента Страницы прочитана, выпусков с меткой: {len(на_странице)}")
    if not п:
        return 0
    print(п["текст"])
    if сухо:
        print("(сухой прогон — ничего не отправлено)")
        return 0

    данные = urllib.parse.urlencode({"message": п["текст"], "access_token": токен}).encode()
    ответ = json.loads(urllib.request.urlopen(f"{API}/{страница}/feed", данные, timeout=120).read())
    ид = ответ.get("id")
    if not ид:
        # Отметку не ставим: пропуск лечится следующим днём очереди, ложная отметка — нет.
        print(f"❌ Meta не вернула id: {ответ}")
        return 1
    п["опубликовано"] = {"дата": сегодня.isoformat(), "id": ид}
    ЗАДАНИЕ.write_text(json.dumps(задание, ensure_ascii=False, indent=1), encoding="utf-8")
    print(f"✅ опубликовано: {ид} — отметка записана, workflow обязан её закоммитить")
    return 0


if __name__ == "__main__":
    sys.exit(главная())
